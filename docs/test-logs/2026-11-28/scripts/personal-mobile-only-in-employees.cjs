const { execSync } = require('child_process');
const sql = (q) => execSync(`mysql -h127.0.0.1 -ucred -pcredpass admin_ui -N -e ${JSON.stringify(q)}`).toString().trim();
const B = 'http://localhost:3200';
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
(async () => {
  const dept = Number(sql("SELECT MAX(id) FROM departments WHERE name='Engineering'"));
  const email = sql(`SELECT u.email FROM users u JOIN departments d ON d.head_user_id=u.id WHERE d.id=${dept}`);
  const a = await (await fetch(B + '/api/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ identifier: email, password: 'Demo#2026pass' }) })).json();
  const H = { Authorization: 'Bearer ' + a.token };
  const team = await (await fetch(B + '/api/my-team', { headers: H })).json();
  const list = team.members || team.people || team.team || (Array.isArray(team) ? team : []);
  const m = list[0]; ok(!!m, 'a team member: ' + (m && m.name));
  const id = m.id || m.employee_id_num || m.employee_db_id;
  const saved = sql(`SELECT CONCAT_WS('|', IFNULL(mobile,''), IFNULL(phone,'')) FROM all_employees WHERE id=${id}`);
  sql(`UPDATE all_employees SET mobile='01711000111', phone='01999000222' WHERE id=${id}`);
  let d = await (await fetch(B + '/api/my-team/' + id, { headers: H })).json();
  ok(d.phone === '01999000222', 'My Team shows the office Contact No.: ' + d.phone);
  ok(!JSON.stringify(d).includes('01711000111'), 'the personal mobile is nowhere in the reply');
  sql(`UPDATE all_employees SET phone=NULL WHERE id=${id}`);
  d = await (await fetch(B + '/api/my-team/' + id, { headers: H })).json();
  ok(d.phone === null && !JSON.stringify(d).includes('01711000111'), 'no office number → no phone (not the personal one)');
  // HR Operations (Superadmin): HR 360 and HR Reports
  sql(`UPDATE all_employees SET mobile='01711000111', phone='01999000222' WHERE id=${id}`);
  const sa = await (await fetch(B + '/api/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ identifier: 'admin@credence.test', password: 'ProbePass123' }) })).json();
  const S = { Authorization: 'Bearer ' + sa.token, 'content-type': 'application/json' };
  const p360 = await (await fetch(B + '/api/hr-ops/p360/' + id, { headers: S })).text();
  ok(p360.includes('01999000222') && !p360.includes('01711000111'), 'HR 360: office Contact No., no personal mobile');
  const rep = await (await fetch(B + '/api/hr-ops/reports/run', { method: 'POST', headers: S, body: JSON.stringify({ columns: ['name', 'blood_group', 'mobile'] }) })).text();
  ok(rep.includes('01999000222') && !rep.includes('01711000111'), 'HR Reports "Contact No." column: office number only');
  const cat = await (await fetch(B + '/api/hr-ops/reports/catalog', { headers: S })).text();
  ok(/"key":"mobile","label":"Contact No\."/.test(cat), 'HR Reports column is labelled "Contact No."');
  const opts = await (await fetch(B + '/api/vehicles/drivers/employee-options', { headers: S })).json();
  const me = (Array.isArray(opts) ? opts : []).find((x) => Number(x.id) === Number(id));
  ok(me && me.mobile === '01999000222', 'Vehicle -> Drivers employee list: office Contact No. (' + (me && me.mobile) + ')');
  const drv = await (await fetch(B + '/api/vehicles/drivers', { headers: S })).text();
  ok(!drv.includes('01711000111'), 'Vehicle -> Drivers list: no personal mobile');
  const [m0, p0] = saved.split('|');
  sql(`UPDATE all_employees SET mobile=${m0 ? `'${m0}'` : 'NULL'}, phone=${p0 ? `'${p0}'` : 'NULL'} WHERE id=${id}`);
})();
